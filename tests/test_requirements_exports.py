"""Les ``requirements.txt`` générés sans ``.in`` (E32) : ``uv export``, ``poetry export``, ``pdm
export``, ``pip-compile pyproject.toml``. Depuis E03, ils restaient des manifestes, et tous leurs
paquets sortaient comme directes ; ce sont des lockfiles du projet, refaits après le sien.

Le mini-projet ``tests/projects/exports`` a été fait par les vrais outils (voir
``tests/projects/README.md``) ; ici, ils sont simulés (``FakeTools``)."""

import json
import re
import shutil
from collections.abc import Callable
from pathlib import Path

import pytest
from conftest import FakeTools, ToolCall

from forceupdate import engine
from forceupdate.models import Gap, Project, Report, Update, UpdateOption, UpdateReason
from forceupdate.parsers import python
from forceupdate.sources.local import LocalSource
from forceupdate.update import lockfiles, writers
from forceupdate.update.lockfiles import LockKind, LockStatus
from forceupdate.update.writers import Choice

PROJECT = Path(__file__).parent / "projects" / "exports"
Tools = Callable[..., FakeTools]


def inventory(root: Path = PROJECT) -> tuple[LocalSource, Report]:
    source = LocalSource(root)
    return source, engine.inventory(source)


def project_of(report: Report, path: str) -> Project:
    return next(project for project in report.projects if project.path == path)


# ---------------------------------------------------------------------------
# L'analyse
# ---------------------------------------------------------------------------


def test_the_headers() -> None:
    def tool(name: str) -> str | None:
        found = python.generated((PROJECT / name / "requirements.txt").read_text("utf-8"))
        return None if found is None else found.tool

    assert tool("uv") == "uv export"
    assert tool("pdm") == "pdm export"
    assert tool("pip-compile") == "pip-compile"
    assert tool("poetry") is None  # poetry export n'écrit pas d'en-tête
    header = python.generated((PROJECT / "pip-compile" / "requirements.txt").read_text("utf-8"))
    assert header is not None
    assert header.command == "pip-compile --output-file=requirements.txt pyproject.toml"
    assert header.sources == ("pyproject.toml",)
    uv = python.generated(
        "# This file was autogenerated by uv via the following command:\n"
        "#    uv pip compile -o requirements.txt setup.cfg --python 3.11\n"
    )
    assert uv is not None and uv.sources == ("setup.cfg",)


@pytest.mark.parametrize(
    ("folder", "lock", "label"),
    [
        ("uv", "uv.lock", "uv export"),
        ("poetry", "poetry.lock", "export"),
        ("pdm", "pdm.lock", "pdm export"),
    ],
)
def test_an_export_is_a_lockfile_of_the_project(folder: str, lock: str, label: str) -> None:
    """Ses paquets ne sont plus des directes : seules celles du ``pyproject.toml`` le sont,
    avec les versions du lockfile de l'outil ; l'export n'est pas relu, une remarque le dit."""
    _, report = inventory()
    project = project_of(report, folder)
    assert project.manifests == [f"{folder}/pyproject.toml"]
    assert sorted(project.lockfiles) == sorted([f"{folder}/{lock}", f"{folder}/requirements.txt"])
    directs = {d.name for d in project.dependencies if d.direct}
    assert "certifi" not in directs and "requests" in directs
    assert all(d.file != f"{folder}/requirements.txt" for d in project.dependencies)
    assert [n.message for n in project.notices if n.file.endswith("requirements.txt")] == [
        f"généré depuis {folder}/{lock} ({label}) : il en a les versions, et se régénère après lui."
    ]


def test_pip_compile_of_a_pyproject() -> None:
    """``pip-compile pyproject.toml`` : le ``.txt`` est le lockfile du ``pyproject.toml``, qui lui
    prend ses versions ; le reste en sont les indirectes."""
    _, report = inventory()
    project = project_of(report, "pip-compile")
    assert project.manifests == ["pip-compile/pyproject.toml"]
    assert project.lockfiles == ["pip-compile/requirements.txt"]
    (requests,) = [d for d in project.dependencies if d.direct]
    assert (requests.name, requests.lockfile) == ("requests", "pip-compile/requirements.txt")
    assert requests.installed is not None
    indirect = {d.name for d in project.dependencies if not d.direct}
    assert {"certifi", "idna", "urllib3", "charset-normalizer"} <= indirect


def test_a_written_requirements_stays_a_manifest(tmp_path: Path) -> None:
    """Un ``requirements.txt`` écrit à la main (des contraintes, ou des versions qui ne sont pas
    celles du lockfile) reste un manifeste ; un export dont le lockfile n'est pas là aussi, avec
    une remarque."""
    root = tmp_path / "poetry"
    shutil.copytree(PROJECT / "poetry", root)
    (root / "requirements.txt").write_text("requests>=2.31\nflask==3.0.0\n", encoding="utf-8")
    _, report = inventory(tmp_path)
    assert "poetry/requirements.txt" in project_of(report, "poetry").manifests

    shutil.copytree(PROJECT / "uv", tmp_path / "uv")
    (tmp_path / "uv" / "uv.lock").unlink()
    _, report = inventory(tmp_path)
    project = project_of(report, "uv")
    assert "uv/requirements.txt" in project.manifests
    assert [n.message for n in project.notices] == [
        "généré par uv export, mais son lockfile n'est pas dans le projet : lu comme un "
        "requirements écrit à la main."
    ]


