def requests_update(project: Project, version: str = "2.99.0") -> Choice:
    """La mise à jour de requests par le lockfile seul (``>=2.31`` l'accepte)."""
    (dependency,) = [d for d in project.dependencies if d.name == "requests" and d.direct]
    option = UpdateOption(
        version=version,
        gap=Gap.MINOR,
        reasons=(UpdateReason.LATEST_MINOR,),
        lockfile=dependency.lockfile,
    )
    update = Update(
        id="requests",
        ecosystem=dependency.ecosystem,
        name="requests",
        direct=True,
        dependencies=(dependency,),
        current_version=dependency.installed,
        options=(option,),
    )
    return project, update, option


def copied(tmp_path: Path, folder: str) -> tuple[Path, LocalSource, Report]:
    root = tmp_path / folder
    shutil.copytree(PROJECT / folder, root)
    source, report = inventory(root)
    return root, source, report


@pytest.mark.parametrize(
    ("folder", "kind", "command", "warnings"),
    [
        (
            "uv",
            LockKind.UV_EXPORT,
            "uv export --format requirements-txt --no-emit-project -o requirements.txt",
            (),
        ),
        (
            "poetry",
            LockKind.POETRY_EXPORT,
            "poetry export -f requirements.txt -o requirements.txt",
            (
                "poetry export demande le plugin poetry-plugin-export (Poetry 2) : sans lui, la "
                "commande échoue, et le lockfile est remis comme avant avec ses manifestes.",
            ),
        ),
        ("pdm", LockKind.PDM_EXPORT, "pdm export -o requirements.txt", ()),
    ],
)
def test_the_export_is_redone_after_its_lockfile(
    tmp_path: Path,
    fake_tools: Tools,
    folder: str,
    kind: LockKind,
    command: str,
    warnings: tuple[str, ...],
) -> None:
    root, source, report = copied(tmp_path, folder)
    fake_tools("uv", "poetry", "pdm")
    choice = requests_update(project_of(report, "."))
    lock, export = lockfiles.plan(source, report, writers.prepare(root, [choice]))
    assert export.lockfile == "requirements.txt"
    assert (export.kind, export.command, export.reason) == (
        kind,
        command,
        f"{lock.lockfile} a changé",
    )
    assert export.inputs == (lock.lockfile,)
    assert export.choices == ()
    assert export.warnings == warnings


def test_uv_export_regenerated(tmp_path: Path, fake_tools: Tools) -> None:
    """``uv lock -P``, puis ``uv export`` avec les options de l'en-tête et ``UV_FROZEN`` (pas
    ``--frozen``, qui passerait dans l'en-tête). Si l'export échoue, ``uv.lock`` est remis."""
    root, source, report = copied(tmp_path, "uv")
    tools = fake_tools("uv")

    def uv(call: ToolCall) -> tuple[int, str, str] | None:
        if call.arguments[0] == "lock":
            lock = call.cwd / "uv.lock"
            text = re.sub(
                r'(name = "requests"\nversion = )"[^"]+"', r'\1"2.99.0"', lock.read_text("utf-8")
            )
            lock.write_text(text, encoding="utf-8")
            return None
        assert call.arguments[0] == "export"
        assert call.env["UV_FROZEN"] == "1"
        target = call.cwd / "requirements.txt"
        target.write_text(
            re.sub(r"^requests==\S+", "requests==2.99.0", target.read_text("utf-8"), flags=re.M),
            encoding="utf-8",
        )
        return None

    tools.handlers["uv"] = uv
    choice = requests_update(project_of(report, "."))
    changes = writers.prepare(root, [choice])
    jobs = lockfiles.plan(source, report, changes)
    writers.write(root, changes)
    lock, export = lockfiles.regenerate(source, report, changes, jobs)
    assert tools.commands() == [
        "uv lock -P requests==2.99.0",
        "uv export --format requirements-txt --no-emit-project -o requirements.txt",
    ]
    assert (lock.status, export.status) == (LockStatus.REGENERATED, LockStatus.REGENERATED)
    assert "requests==2.99.0" in (root / "requirements.txt").read_text("utf-8")
    assert export.changed == ("requests 2.34.2 → 2.99.0",)

    before = {name: (root / name).read_bytes() for name in ("uv.lock", "requirements.txt")}
    tools.handlers["uv"] = lambda call: (
        uv(call) if call.arguments[0] == "lock" else (2, "", "uv: export impossible")
    )
    source, report = inventory(root)
    choice = requests_update(project_of(report, "."), "3.0.0")
    changes = writers.prepare(root, [choice])
    jobs = lockfiles.plan(source, report, changes)
    writers.write(root, changes)
    lock, export = lockfiles.regenerate(source, report, changes, jobs)
    assert export.status is LockStatus.FAILED and lock.status is LockStatus.UNDONE
    assert {name: (root / name).read_bytes() for name in before} == before


def test_pip_compile_of_a_pyproject_is_recompiled(tmp_path: Path, fake_tools: Tools) -> None:
    root, source, report = copied(tmp_path, "pip-compile")
    fake_tools("pip-compile")
    choice = requests_update(project_of(report, "."))
    (job,) = lockfiles.plan(source, report, writers.prepare(root, [choice]))
    assert (job.kind, job.sources) == (LockKind.PIP_COMPILE, ("pyproject.toml",))
    assert job.command == (
        "pip-compile --output-file requirements.txt pyproject.toml -P requests==2.99.0"
    )


def test_export_options_follow_the_file() -> None:
    """Sans en-tête : les empreintes, les paquets de dev, d'après le fichier."""
    options, dropped = lockfiles._uv_export_options(
        "uv export --frozen --format=requirements-txt -o req.txt --no-hashes --emit-index-url "
        "--group docs",
        "requirements.txt",
    )
    # Telles qu'écrites, dans leur ordre : uv recopie sa commande dans l'en-tête.
    assert options == [
        "--format=requirements-txt",
        "-o",
        "requirements.txt",
        "--no-hashes",
        "--group",
        "docs",
    ]
    assert dropped == ["--emit-index-url"]
    options, _ = lockfiles._uv_export_options("uv export --format requirements-txt", "r.txt")
    assert options == ["--format", "requirements-txt", "-o", "r.txt"]


def test_poetry_and_pdm_options_from_the_content(tmp_path: Path, fake_tools: Tools) -> None:
    """``poetry export`` sans empreintes, avec le groupe dev ; ``pdm export`` sans dev :
    ``--without-hashes``, ``--with dev``, ``--prod``."""
    root, _, _ = copied(tmp_path, "poetry")
    lines = [
        line.split(" ;")[0].strip()
        for line in (PROJECT / "poetry" / "requirements.txt").read_text("utf-8").splitlines()
        if not line.startswith(" ") and "==" in line
    ]
    lock = (root / "poetry.lock").read_text("utf-8")
    pytest_version = re.search(r'name = "pytest"\nversion = "([^"]+)"', lock)
    assert pytest_version is not None
    (root / "requirements.txt").write_text(
        "\n".join([*lines, f"pytest=={pytest_version[1]}"]) + "\n", encoding="utf-8"
    )
    fake_tools("poetry")
    source, report = inventory(root)
    choice = requests_update(project_of(report, "."))
    _, export = lockfiles.plan(source, report, writers.prepare(root, [choice]))
    assert export.command == (
        "poetry export -f requirements.txt -o requirements.txt --without-hashes --with dev"
    )

    root, _, _ = copied(tmp_path, "pdm")
    text = (root / "requirements.txt").read_text("utf-8")
    kept = re.sub(
        r"^(pytest|iniconfig|pluggy|packaging|pygments|colorama)==[^\n]*(\n    [^\n]*)*\n",
        "",
        text,
        flags=re.M,
    )
    (root / "requirements.txt").write_text(kept, encoding="utf-8")
    fake_tools("pdm")
    source, report = inventory(root)
    choice = requests_update(project_of(report, "."))
    _, export = lockfiles.plan(source, report, writers.prepare(root, [choice]))
    assert export.command == "pdm export -o requirements.txt --prod"
    assert json.dumps(export.options)  # des chaînes, rien d'autre
