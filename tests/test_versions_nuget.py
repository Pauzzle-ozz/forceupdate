@pytest.mark.parametrize(("spec", "expected"), RANGES)
def test_ranges_like_version_range(spec: str, expected: tuple[str, str, str | None] | None) -> None:
    if expected is None:
        with pytest.raises(InvalidConstraint):
            NUGET.parse_constraint(spec)
        return
    shape, accepted, chosen = expected
    parsed = NUGET.parse_constraint(spec)
    assert _shape(parsed) == shape
    assert "".join("1" if NUGET.satisfies(spec, v) else "0" for v in RANGE_VERSIONS) == accepted
    assert NUGET.chosen(spec, RANGE_VERSIONS) == chosen


