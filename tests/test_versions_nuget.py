_BEHAVIORS = {
    Float.PRERELEASE: "Prerelease",
    Float.REVISION: "Revision",
    Float.PATCH: "Patch",
    Float.MINOR: "Minor",
    Float.MAJOR: "Major",
    Float.ABSOLUTE_LATEST: "AbsoluteLatest",
    Float.PRERELEASE_REVISION: "PrereleaseRevision",
    Float.PRERELEASE_PATCH: "PrereleasePatch",
    Float.PRERELEASE_MINOR: "PrereleaseMinor",
    Float.PRERELEASE_MAJOR: "PrereleaseMajor",
}
"""Les noms de ``NuGetVersionFloatBehavior``, tels que les donne l'oracle."""


def _shape(parsed: NuGetRange) -> str:
    opening = "[" if parsed.minimum_inclusive else "("
    closing = "]" if parsed.maximum_inclusive else ")"
    low = "" if parsed.minimum is None else parsed.minimum.normalized
    high = "" if parsed.maximum is None else parsed.maximum.normalized
    floated = f" {_BEHAVIORS[parsed.float.behavior]}" if parsed.floating and parsed.float else ""
    return f"{opening}{low}, {high}{closing}{floated}"


